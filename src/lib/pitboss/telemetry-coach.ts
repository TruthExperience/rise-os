// Builds the system prompt with the correct speed-unit instruction baked
// in. With speedUnit selectable per-report, a hardcoded unit label would
// have the LLM writing "km/h" in its prose right next to mph numbers.
function buildCoachSystemPrompt(speedUnit: SpeedUnit): string {
  const unitLabel = speedUnitLabel(speedUnit);
  return `You are PitBoss's sim-racing driving coach for F1 UDP telemetry.
You are given the ALREADY-COMPUTED structured output of a deterministic telemetry analysis for one lap: lap time, an optional comparison against a reference lap, a per-corner breakdown (braking point/pressure/duration, trail-brake %, min corner speed, throttle application point, distance from apex to throttle, full-throttle point, throttle smoothness 0-1, and any detected issues), and a per-straight breakdown (length, top speed and where it was reached, average throttle 0-1, % of the straight with DRS active, and time delta vs the reference lap across that straight if available).

Your job is ONLY to interpret these numbers in plain, encouraging but honest coaching language. Do not invent facts, distances, or times that are not present in the data. Do not contradict the numbers given. If a value is missing or looks like a sensor gap (e.g. fullThrottleDist is null), say so rather than guessing.

Corner numbering: each corner object has an "id" field starting at 0 — this is an internal array index, NOT the display number. Always refer to corners using id+1 in your prose (e.g. id 0 is "Corner 1", id 2 is "Corner 3"), to match what the driver sees on screen. Never write "corner 0" or any other 0-indexed reference. Straights should be referred to descriptively (e.g. "the straight after Corner 3") rather than by a straight id number, since the driver doesn't see straight numbers on screen.

Field names are internal variable names, not driving vocabulary — describe what they mean in plain racing language instead of naming the field. For example, say "throttle came on a bit late after the apex" rather than "distFromApexToThrottle was high".

How the measurements are defined (use this to interpret them correctly):
- A straight's avgThrottle is measured only over the flat-out part: from the first moment the car reaches full throttle to the start of the next braking zone. The exit ramp out of the previous corner and the braking zone are excluded, so a value clearly below 0.9 means real lifts in the middle of the straight, while a value near 1.0 means the driver was flat out.
- distFromApexToThrottle is how far past the apex the driver first reached a sustained 30%+ throttle. A value of 0 means the driver was already on meaningful throttle at the apex, which is good and is not missing data. Only call the throttle "late" when this number is genuinely large.
- An engine over-rev issue means the engine sat on the rev limiter for several frames in one gear — a missed or late upshift.
- Lockup issues are a proxy (a sudden collapse in braking g under heavy braking), not a certainty. Word them as "possible" lockups.

Units: distances in meters, speeds in ${unitLabel} (all speed values given — topSpeed, minSpeedInCorner — are already converted to this unit; use it consistently in your prose), times in seconds, angles in degrees, pressures/smoothness/throttle on a 0-1 scale.

Respond with ONLY a single JSON object, no markdown fences, no prose outside the JSON, matching exactly this shape:
{
  "summary": "2-4 sentence overall lap summary",
  "cornerNotes": { "<cornerId>": "1-3 sentence coaching note for that corner", ... one entry per corner id given ... },
  "cornerSuggestions": { "<cornerId>": "1 short, concrete, single-focus next-lap tip for that corner — the ONE thing to try differently, or a short affirmation if execution was clean", ... one entry per corner id given ... },
  "straightNotes": { "<straightId>": "1-2 sentence note about that straight — top speed reached, throttle discipline, DRS usage, and/or time delta if given", ... one entry per straight id given ... },
  "straightSuggestions": { "<straightId>": "1 short, concrete tip for that straight, or a short affirmation if it was clean", ... one entry per straight id given ... },
  "suggestions": ["3-5 short, concrete, prioritized next-lap tips covering the whole lap, each grounded in a specific number, corner, or straight from the data above, described in plain racing language rather than field names. Order from highest-impact first. Do not repeat the summary verbatim."]
}`;
}

function stripJsonFences(text: string): string {
  return text.replace(/```json|```/g, '').trim();
}

// Recovers a JSON object embedded in surrounding prose. Some models return
// reasoning text before the actual JSON answer, so the whole response isn't
// pure JSON. Finds the last balanced {...} block by scanning backward from
// the final '}' and tracking brace depth, and parses just that substring.
function extractTrailingJsonObject(text: string): string | null {
  const lastBrace = text.lastIndexOf('}');
  if (lastBrace === -1) return null;
  let depth = 0;
  for (let i = lastBrace; i >= 0; i--) {
    if (text[i] === '}') depth++;
    else if (text[i] === '{') {
      depth--;
      if (depth === 0) return text.slice(i, lastBrace + 1);
    }
  }
  return null;
}

function isStringRecord(v: unknown): v is Record<string, string> {
  return !!v && typeof v === 'object' && !Array.isArray(v) && Object.values(v).every((x) => typeof x === 'string');
}

/**
 * Deterministic suggestions builder — ranks the most actionable findings
 * from the structured analysis into 3-5 concrete top-level tips. Used as
 * the fallback when no LLM is available or a part comes back unparseable.
 */
function buildDeterministicSuggestions(input: NarrativeInput): string[] {
  const suggestions: string[] = [];

  if (input.comparison?.biggestLossZone) {
    const z = input.comparison.biggestLossZone;
    suggestions.push(
      `Focus here first: ${z.lostSeconds.toFixed(2)}s lost between ${z.startDist.toFixed(0)}m and ${z.endDist.toFixed(0)}m vs lap ${input.referenceLapNum}.`
    );
  }

  const brakedCorners = input.corners.filter((c) => c.brakeDurationMeters > 0);
  if (brakedCorners.length > 0) {
    const worstTrail = brakedCorners.reduce((a, b) => (a.trailBrakePercent < b.trailBrakePercent ? a : b));
    if (worstTrail.trailBrakePercent < 0.3) {
      suggestions.push(
        `Corner ${worstTrail.id + 1}: only ${(worstTrail.trailBrakePercent * 100).toFixed(0)}% trail brake — carry a bit more brake into the turn to rotate the car earlier.`
      );
    }
  }

  if (input.corners.length > 0) {
    const roughest = input.corners.reduce((a, b) => (a.applicationSmoothness < b.applicationSmoothness ? a : b));
    if (roughest.applicationSmoothness < 0.5) {
      suggestions.push(
        `Corner ${roughest.id + 1}: throttle application is inconsistent on exit — smooth the initial squeeze before going to full throttle.`
      );
    }

    const latestThrottle = input.corners.reduce((a, b) => (a.distFromApexToThrottle > b.distFromApexToThrottle ? a : b));
    if (latestThrottle.distFromApexToThrottle > 20) {
      suggestions.push(
        `Corner ${latestThrottle.id + 1}: sustained throttle came on ${latestThrottle.distFromApexToThrottle.toFixed(0)}m after the apex — there may be time available getting back to power sooner.`
      );
    }
  }

  const liftingStraight = input.straights.find((s) => s.avgThrottle < 0.9);
  if (liftingStraight) {
    suggestions.push(
      `Throttle wasn't fully pinned on the ${liftingStraight.lengthMeters.toFixed(0)}m straight starting around ${liftingStraight.startDist.toFixed(0)}m — check for an unnecessary lift.`
    );
  }

  const majorIssues = input.generalIssues.filter((i) => i.severity === 'major');
  if (majorIssues.length > 0) {
    const kinds = new Set(majorIssues.map((i) => i.kind));
    if (kinds.has('lockup')) {
      suggestions.push(`Possible lockups detected this lap — ease initial brake pressure to avoid flat-spotting the tyres.`);
    }
    if (kinds.has('snap_correction')) {
      suggestions.push(`The rear stepped out at least once — consider slightly less aggressive turn-in or throttle mid-corner.`);
    }
  }

  if (input.generalIssues.some((i) => i.kind === 'engine_over_rev')) {
    suggestions.push(`You sat on the rev limiter at least once — shift up a touch earlier.`);
  }

  return suggestions.slice(0, 5);
}

function deterministicCornerSuggestion(c: NarrativeCornerInput): string {
  const majorIssue = c.issues.find((iss) => iss.severity === 'major');
  if (majorIssue) {
    if (majorIssue.kind === 'lockup') return 'Ease initial brake pressure here to avoid the possible lockup.';
    if (majorIssue.kind === 'snap_correction') return 'A smoother initial input here should keep the rear settled.';
    if (majorIssue.kind === 'engine_over_rev') return 'Shift a touch earlier here to stop sitting on the limiter.';
  }
  if (c.brakeDurationMeters > 0 && c.trailBrakePercent < 0.3) {
    return 'Carry a bit more brake into the corner to rotate the car earlier.';
  }
  if (c.applicationSmoothness < 0.5) {
    return 'Smooth out the throttle application on exit.';
  }
  if (c.distFromApexToThrottle > 20) {
    return 'Get back to power sooner after the apex.';
  }
  return 'Solid execution here — no clear time on the table.';
}

function deterministicStraightNote(s: NarrativeStraightInput, unitLabel: string): string {
  const parts: string[] = [];
  parts.push(`${s.lengthMeters.toFixed(0)}m straight, top speed ${s.topSpeed.toFixed(0)} ${unitLabel} at ${s.topSpeedDist.toFixed(0)}m.`);
  if (s.drsActivePercent > 0) {
    parts.push(`DRS active ${(s.drsActivePercent * 100).toFixed(0)}% of the way.`);
  }
  if (s.deltaVsReferenceSeconds != null) {
    const sign = s.deltaVsReferenceSeconds >= 0 ? '+' : '';
    parts.push(`${sign}${s.deltaVsReferenceSeconds.toFixed(3)}s vs the reference lap here.`);
  }
  return parts.join(' ');
}

function deterministicStraightSuggestion(s: NarrativeStraightInput): string {
  if (s.avgThrottle < 0.9) {
    return 'Throttle was not held fully flat once you were up to speed — check for an unnecessary lift.';
  }
  if (s.deltaVsReferenceSeconds != null && s.deltaVsReferenceSeconds > 0.05) {
    return `Losing ${s.deltaVsReferenceSeconds.toFixed(2)}s here vs the reference lap — likely down to exit speed from the corner before it, not this straight itself.`;
  }
  return 'Full throttle held cleanly — nothing to change here.';
}

/**
 * Deterministic fallback narrative — used when no LLM is configured or every
 * LLM call fails/times out/is unparseable. Template-built from the same
 * structured input the LLM would have received, so the UI always gets a
 * usable summary, per-corner and per-straight notes/suggestions, and
 * top-level suggestions.
 */
function buildDeterministicNarrative(input: NarrativeInput): CoachingNarrative {
  const unitLabel = speedUnitLabel(input.speedUnit);
  const summaryParts: string[] = [];
  summaryParts.push(`Lap ${input.lapNum}: ${input.lapTime.toFixed(3)}s${input.lapValid ? '' : ' (invalid)'}.`);
  if (input.comparison) {
    const sign = input.comparison.totalDeltaSeconds >= 0 ? '+' : '';
    summaryParts.push(`${sign}${input.comparison.totalDeltaSeconds.toFixed(3)}s vs lap ${input.referenceLapNum}.`);
    if (input.comparison.biggestLossZone) {
      summaryParts.push(
        `Biggest loss: ${input.comparison.biggestLossZone.lostSeconds.toFixed(2)}s between ${input.comparison.biggestLossZone.startDist.toFixed(0)}m–${input.comparison.biggestLossZone.endDist.toFixed(0)}m.`
      );
    }
  }
  const majorIssueCount = input.generalIssues.filter((i) => i.severity === 'major').length;
  if (majorIssueCount > 0) {
    summaryParts.push(`${majorIssueCount} major issue(s) detected this lap.`);
  }

  const cornerNotes = new Map<number, string>();
  const cornerSuggestions = new Map<number, string>();
  for (const c of input.corners) {
    const parts: string[] = [];
    parts.push(`Braked at ${c.brakePointDist.toFixed(0)}m, peak ${(c.brakePeakPressure * 100).toFixed(0)}% brake pressure, min speed ${c.minSpeedInCorner.toFixed(0)} ${unitLabel}.`);
    parts.push(`Trail-braked through ${(c.trailBrakePercent * 100).toFixed(0)}% of the braking zone.`);
    parts.push(
      c.fullThrottleDist != null
        ? c.distFromApexToThrottle < 1
          ? `Already on sustained throttle at the apex, full throttle by ${c.fullThrottleDist.toFixed(0)}m.`
          : `Sustained throttle ${c.distFromApexToThrottle.toFixed(0)}m after the apex, full throttle by ${c.fullThrottleDist.toFixed(0)}m.`
        : `Full throttle not reached before the next braking zone.`
    );
    if (c.issues.length > 0) {
      parts.push(`${c.issues.length} issue(s) flagged in this corner.`);
    }
    cornerNotes.set(c.id, parts.join(' '));
    cornerSuggestions.set(c.id, deterministicCornerSuggestion(c));
  }

  const straightNotes = new Map<number, string>();
  const straightSuggestions = new Map<number, string>();
  for (const s of input.straights) {
    straightNotes.set(s.id, deterministicStraightNote(s, unitLabel));
    straightSuggestions.set(s.id, deterministicStraightSuggestion(s));
  }

  return {
    summaryText: summaryParts.join(' '),
    cornerNotes,
    cornerSuggestions,
    straightNotes,
    straightSuggestions,
    suggestions: buildDeterministicSuggestions(input),
    source: 'deterministic',
  };
}

// -----------------------------------------------------------------------
// LLM narrative — Claude first, Groq second, deterministic template last.
//
// The narrative is split into three requests (overview / corners /
// straights) so each response is small enough to finish quickly and so a
// failure in one part only drops that part to the template, not the whole
// report. Claude runs the three in parallel; Groq runs them one after
// another by default (see runNarrativeParts) to stay under the free tier's
// tokens-per-minute limit, with one retry after a 429.
//
// Env:
//   ANTHROPIC_API_KEY   Claude. COACH_MODEL optionally overrides the model id.
//   GROQ_API_KEY        Groq. GROQ_COACH_MODEL optionally overrides the model.
// The coach route must allow >30s (see maxDuration in its route.ts).
// -----------------------------------------------------------------------

const COACH_MODEL = process.env.COACH_MODEL || 'claude-sonnet-5-5';
const COACH_CALL_TIMEOUT_MS = 40_000;

const GROQ_MODEL = process.env.GROQ_COACH_MODEL || 'llama-3.3-70b-versatile';
const GROQ_CALL_TIMEOUT_MS = 30_000;
const GROQ_MAX_RETRY_WAIT_SECONDS = 20;

const COACH_QUALITY_ADDENDUM = `

Coaching standards (apply to every note and tip you write):
- Rank by lap time. Put the biggest time losses first, using the comparison zones, sector deltas and per-straight deltas when they are given. Say roughly how much time is at stake only when a number in the data supports it.
- Explain cause and effect: what the driver did, why it costs time, and what the effect is on the next phase of the corner or the straight that follows.
- Make every tip specific and testable on the next lap (a brake marker, a throttle point, a trail-brake release, a minimum-speed target). Prefer targets taken from the reference lap numbers when one is provided.
- Name what was done well when execution is clean, so the driver knows what to keep.
- Be a coach, not a report: direct, encouraging, never generic, and never repeat the same sentence shape across corners.
- If the data shows a sensor gap or a missing value, say it cannot be judged rather than guessing.`;

type NarrativePart = 'overview' | 'corners' | 'straights';

const PART_INSTRUCTION: Record<NarrativePart, string> = {
  overview:
    '\n\nFor THIS request return ONLY a JSON object with exactly these two keys: "summary" and "suggestions". Omit every other key.',
  corners:
    '\n\nFor THIS request return ONLY a JSON object with exactly these two keys: "cornerNotes" and "cornerSuggestions". Omit every other key.',
  straights:
    '\n\nFor THIS request return ONLY a JSON object with exactly these two keys: "straightNotes" and "straightSuggestions". Omit every other key.',
};

type CoachCaller = (system: string, payload: object, maxTokens: number) => Promise<string | null>;

async function callClaudeForCoach(system: string, payload: object, maxTokens: number): Promise<string | null> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) return null;

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), COACH_CALL_TIMEOUT_MS);
  try {
    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'x-api-key': apiKey,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: COACH_MODEL,
        max_tokens: maxTokens,
        system,
        messages: [{ role: 'user', content: JSON.stringify(payload) }],
      }),
      signal: controller.signal,
    });
    if (!res.ok) {
      console.error('[telemetry-coach] Claude call failed:', res.status, (await res.text()).slice(0, 500));
      return null;
    }
    const data: any = await res.json();
    const text = Array.isArray(data?.content)
      ? data.content
          .filter((b: any) => b?.type === 'text' && typeof b.text === 'string')
          .map((b: any) => b.text)
          .join('')
      : '';
    return text.trim() ? text : null;
  } catch (err) {
    console.error('[telemetry-coach] Claude call threw:', err);
    return null;
  } finally {
    clearTimeout(timer);
  }
}

// Groq exposes an OpenAI-compatible chat completions endpoint. JSON mode
// (response_format json_object) keeps the model from wrapping the answer in
// prose; the system prompt already says "JSON", which JSON mode requires.
// llama-3.3-70b-versatile is not a reasoning model, so it doesn't spend
// output budget on hidden thinking tokens. One retry after a 429 (free-tier
// rate limit), waiting for the server's retry-after (capped).
async function callGroqForCoach(system: string, payload: object, maxTokens: number): Promise<string | null> {
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) return null;

  for (let attempt = 0; attempt < 2; attempt++) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), GROQ_CALL_TIMEOUT_MS);
    try {
      const res = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          authorization: `Bearer ${apiKey}`,
        },
        body: JSON.stringify({
          model: GROQ_MODEL,
          max_tokens: maxTokens,
          temperature: 0.4,
          response_format: { type: 'json_object' },
          messages: [
            { role: 'system', content: system },
            { role: 'user', content: JSON.stringify(payload) },
          ],
        }),
        signal: controller.signal,
      });

      if (res.status === 429 && attempt === 0) {
        const retryAfter = Number(res.headers.get('retry-after'));
        const waitSeconds = Math.min(Math.max(Number.isFinite(retryAfter) && retryAfter > 0 ? retryAfter : 8, 1), GROQ_MAX_RETRY_WAIT_SECONDS);
        console.error(`[telemetry-coach] Groq rate limited, retrying in ${waitSeconds}s`);
        await new Promise((resolve) => setTimeout(resolve, waitSeconds * 1000));
        continue;
      }

      if (!res.ok) {
        console.error('[telemetry-coach] Groq call failed:', res.status, (await res.text()).slice(0, 500));
        return null;
      }
      const data: any = await res.json();
      const text = data?.choices?.[0]?.message?.content;
      return typeof text === 'string' && text.trim() ? text : null;
    } catch (err) {
      console.error('[telemetry-coach] Groq call threw:', err);
      return null;
    } finally {
      clearTimeout(timer);
    }
  }
  return null;
}

function parseJsonObjectLoose(raw: string | null): any | null {
  if (!raw) return null;
  const cleaned = stripJsonFences(raw);
  try {
    return JSON.parse(cleaned);
  } catch {
    // fall through to extraction
  }
  const extracted = extractTrailingJsonObject(cleaned);
  if (!extracted) return null;
  try {
    return JSON.parse(extracted);
  } catch {
    return null;
  }
}

function recordToNumberMap(rec: Record<string, string>): Map<number, string> {
  const m = new Map<number, string>();
  for (const [key, note] of Object.entries(rec)) {
    const id = Number(key);
    if (Number.isFinite(id)) m.set(id, note);
  }
  return m;
}

async function generateNarrativeWithLLM(
  input: NarrativeInput,
  call: CoachCaller,
  providerLabel: string,
  sequential: boolean
): Promise<CoachingNarrative | null> {
  const system = buildCoachSystemPrompt(input.speedUnit) + COACH_QUALITY_ADDENDUM;
  const lapContext = {
    lapNum: input.lapNum,
    lapTime: input.lapTime,
    lapValid: input.lapValid,
    referenceLapNum: input.referenceLapNum,
    speedUnit: input.speedUnit,
    comparison: input.comparison,
    generalIssues: input.generalIssues,
  };

  const tasks: Array<() => Promise<string | null>> = [
    () => call(system + PART_INSTRUCTION.overview, input, 1200),
    () =>
      input.corners.length > 0
        ? call(system + PART_INSTRUCTION.corners, { ...lapContext, corners: input.corners }, 2500)
        : Promise.resolve(null),
    () =>
      input.straights.length > 0
        ? call(system + PART_INSTRUCTION.straights, { ...lapContext, straights: input.straights }, 1500)
        : Promise.resolve(null),
  ];

  let results: Array<string | null>;
  if (sequential) {
    results = [];
    for (const task of tasks) results.push(await task());
  } else {
    results = await Promise.all(tasks.map((task) => task()));
  }
  const [overviewRaw, cornersRaw, straightsRaw] = results;

  const overview = parseJsonObjectLoose(overviewRaw);
  const cornersParsed = parseJsonObjectLoose(cornersRaw);
  const straightsParsed = parseJsonObjectLoose(straightsRaw);

  const overviewOk =
    !!overview &&
    typeof overview.summary === 'string' &&
    Array.isArray(overview.suggestions) &&
    overview.suggestions.length > 0 &&
    overview.suggestions.every((x: unknown) => typeof x === 'string');
  const cornersOk =
    !!cornersParsed && isStringRecord(cornersParsed.cornerNotes) && isStringRecord(cornersParsed.cornerSuggestions);
  const straightsOk =
    !!straightsParsed && isStringRecord(straightsParsed.straightNotes) && isStringRecord(straightsParsed.straightSuggestions);

  if (!overviewOk && !cornersOk && !straightsOk) {
    console.error(`[telemetry-coach] all ${providerLabel} narrative parts failed or were unparseable`);
    return null;
  }

  // Anything a failed part leaves out is filled per item by the existing
  // deterministic fallback in buildCoachingReport.
  const det = buildDeterministicNarrative(input);
  return {
    summaryText: overviewOk ? overview.summary : det.summaryText,
    suggestions: overviewOk ? overview.suggestions : det.suggestions,
    cornerNotes: cornersOk ? recordToNumberMap(cornersParsed.cornerNotes) : new Map(),
    cornerSuggestions: cornersOk ? recordToNumberMap(cornersParsed.cornerSuggestions) : new Map(),
    straightNotes: straightsOk ? recordToNumberMap(straightsParsed.straightNotes) : new Map(),
    straightSuggestions: straightsOk ? recordToNumberMap(straightsParsed.straightSuggestions) : new Map(),
    source: 'llm',
  };
}

async function generateCoachingNarrative(input: NarrativeInput): Promise<CoachingNarrative> {
  // 1. Claude (parallel parts). Skipped when no key is configured.
  if (process.env.ANTHROPIC_API_KEY) {
    const viaClaude = await generateNarrativeWithLLM(input, callClaudeForCoach, 'Claude', false);
    if (viaClaude) return viaClaude;
  }

  // 2. Groq (sequential parts, free tier). Skipped when no key is configured.
  if (process.env.GROQ_API_KEY) {
    const viaGroq = await generateNarrativeWithLLM(input, callGroqForCoach, 'Groq', true);
    if (viaGroq) return viaGroq;
  }

  // 3. Deterministic template.
  return buildDeterministicNarrative(input);
}

