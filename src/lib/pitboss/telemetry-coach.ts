export type SpeedUnit = 'kph' | 'mph';

// =======================================================================
// Speed unit conversion — all raw telemetry (frame.speed, F1 UDP's
// m_speed field) and all internal detection thresholds (MIN_APEX_SPEED_
// DROP_KMH, etc.) are km/h always. Conversion to mph happens exactly once,
// at the buildCoachingReport boundary, only on values that get
// returned/displayed — never inside the detection math itself. See
// CoachingReport.speedUnit's doc comment for the contract.
// =======================================================================

const KPH_TO_MPH = 1 / 1.609344;

function convertSpeed(kph: number, unit: SpeedUnit): number {
  return unit === 'mph' ? kph * KPH_TO_MPH : kph;
}

function speedUnitLabel(unit: SpeedUnit): string {
  return unit === 'mph' ? 'mph' : 'km/h';
}

// =======================================================================
// Shared thresholds (declared up here so every section below can use them
// without relying on declaration order).
// =======================================================================

const STEER_THRESHOLD_DEG = 15; // realistic minimum steering input for an actual corner
const BRAKE_THRESHOLD = 0.1; // 0-1 scale
const FULL_THROTTLE_THRESHOLD = 0.95;

// =======================================================================
// Distance-domain resampling — the backbone of lap comparison. Frames
// arrive at fixed time intervals, not fixed distance intervals, so two
// laps rarely share sample points. Resample both onto a common distance
// grid before comparing.
// =======================================================================

// A grid point interpolated across a large real-time gap between the two
// bracketing frames (e.g. a dropped-UDP-packet capture dropout) is not a
// trustworthy value — see DeltaPoint.deltaSeconds in
// telemetry-coach-types.ts, which documents exactly this contract.
// Confirmed against real uploads: capture gaps are bursty (tight clusters
// of 16-50ms frames interrupted by multi-second blackouts), not a uniform
// downsample, so this has to be measured per-point, not assumed constant.
const SOURCE_GAP_UNRELIABLE_SECONDS = 0.5;

interface ResampledSpeedPoint {
  speed: number;
  /**
   * Estimated real-world time gap (seconds) between the two actual
   * telemetry frames bracketing this grid point, derived from their
   * distance gap and average speed. Large values mean this point was
   * linearly interpolated across a real capture gap, not measured.
   */
  sourceGapSeconds: number;
}

function resampleOntoGrid(frames: TelemetryFrame[], grid: number[]): ResampledSpeedPoint[] {
  // Linear-interpolates speed (raw km/h, straight from the F1 UDP
  // m_speed field) at each grid distance. Frames assumed sorted by dist
  // ascending.
  const result: ResampledSpeedPoint[] = [];
  let i = 0;
  for (const d of grid) {
    while (i < frames.length - 2 && frames[i + 1].dist < d) i++;
    const a = frames[i];
    const b = frames[Math.min(i + 1, frames.length - 1)];
    if (b.dist === a.dist) {
      result.push({ speed: a.speed, sourceGapSeconds: 0 });
      continue;
    }
    const t = (d - a.dist) / (b.dist - a.dist);
    const speed = a.speed + t * (b.speed - a.speed);
    // Convert km/h -> m/s before using speed to turn a distance gap
    // between the two real bracketing frames into a time-gap estimate.
    const avgSpeedMs = (a.speed + b.speed) / 2 / 3.6;
    const sourceGapSeconds = avgSpeedMs > 0.1 ? (b.dist - a.dist) / avgSpeedMs : 0;
    result.push({ speed, sourceGapSeconds });
  }
  return result;
}

function buildDistanceGrid(frames: TelemetryFrame[], stepMeters = 2): number[] {
  const maxDist = frames[frames.length - 1]?.dist ?? 0;
  const grid: number[] = [];
  for (let d = 0; d <= maxDist; d += stepMeters) grid.push(d);
  return grid;
}

/**
 * Converts a speed trace over a distance grid into cumulative time at
 * each grid point (time = distance / speed, integrated). Speed of 0
 * is clamped to a small epsilon to avoid division by zero (shouldn't
 * happen mid-lap, but stationary/pit-in frames could produce it).
 */
function speedTraceToCumulativeTime(speeds: number[], stepMeters: number): number[] {
  const EPSILON = 0.5; // m/s floor
  const cumulative: number[] = [0];
  for (let i = 1; i < speeds.length; i++) {
    // speeds[] is raw km/h (frame.speed, straight from F1 UDP's m_speed
    // field) — must convert to m/s before dividing distance by it.
    // Missing this made every dt, and therefore every deltaCurve point,
    // zone, and per-straight delta downstream, too small by ~3.6x.
    const avgSpeedMs = Math.max((speeds[i - 1] + speeds[i]) / 2 / 3.6, EPSILON);
    const dt = stepMeters / avgSpeedMs;
    cumulative.push(cumulative[i - 1] + dt);
  }
  return cumulative;
}

// =======================================================================
// 1. Lap comparison
// =======================================================================

export function compareLaps(lapA: TelemetryLap, lapB: TelemetryLap, stepMeters = 2): LapComparison {
  // getTelemetrySession() can legitimately produce a lap with zero frames
  // (payload?.telemetry ?? [] in lib/telemetry.ts). Without this guard,
  // resampleOntoGrid's frames[0] access throws an unhandled TypeError
  // instead of a message that tells the caller which lap is the problem.
  if (lapA.frames.length === 0 || lapB.frames.length === 0) {
    const badLap = lapA.frames.length === 0 ? lapA.lapNum : lapB.lapNum;
    throw new Error(`Cannot compare laps: lap ${badLap} has no telemetry frames.`);
  }

  const grid = buildDistanceGrid(
    lapA.frames.length > lapB.frames.length ? lapA.frames : lapB.frames,
    stepMeters
  );

  const resampledA = resampleOntoGrid(lapA.frames, grid);
  const resampledB = resampleOntoGrid(lapB.frames, grid);

  const timeA = speedTraceToCumulativeTime(resampledA.map((p) => p.speed), stepMeters);
  const timeB = speedTraceToCumulativeTime(resampledB.map((p) => p.speed), stepMeters);

  const deltaCurve: DeltaPoint[] = grid.map((dist, i) => {
    // If either lap's value at this grid point was interpolated across a
    // real capture gap, the delta here isn't measured data — it's a
    // straight line drawn through an unknown braking/apex/exit sequence.
    // Null it out rather than presenting invented smoothness as fact.
    const unreliable =
      resampledA[i].sourceGapSeconds > SOURCE_GAP_UNRELIABLE_SECONDS ||
      resampledB[i].sourceGapSeconds > SOURCE_GAP_UNRELIABLE_SECONDS;
    return {
      dist,
      deltaSeconds: unreliable ? null : timeB[i] - timeA[i],
    };
  });

  const totalDeltaSeconds = lapB.lapTime - lapA.lapTime;

  let biggestGainZone: LapComparison['biggestGainZone'] = null;
  let biggestLossZone: LapComparison['biggestLossZone'] = null;
  let minDelta = 0;
  let maxDelta = 0;
  let minIdx = 0;
  let maxIdx = 0;

  for (let i = 0; i < deltaCurve.length; i++) {
    const delta = deltaCurve[i].deltaSeconds;
    if (delta === null) continue;
    if (delta < minDelta) {
      minDelta = delta;
      minIdx = i;
    }
    if (delta > maxDelta) {
      maxDelta = delta;
      maxIdx = i;
    }
  }

  if (minDelta < -0.05) {
    // lapB gained time relative to lapA up to this point — find where the
    // gaining streak started by walking backward while delta keeps
    // improving. Stops at the first null boundary too, since we can't
    // compare across an unreliable point.
    let start = minIdx;
    while (
      start > 0 &&
      deltaCurve[start - 1].deltaSeconds !== null &&
      deltaCurve[start].deltaSeconds !== null &&
      (deltaCurve[start - 1].deltaSeconds as number) >= (deltaCurve[start].deltaSeconds as number)
    ) {
      start--;
    }
    biggestGainZone = {
      startDist: deltaCurve[start].dist,
      endDist: deltaCurve[minIdx].dist,
      gainedSeconds: Math.abs(minDelta),
    };
  }

  if (maxDelta > 0.05) {
    let start = maxIdx;
    while (
      start > 0 &&
      deltaCurve[start - 1].deltaSeconds !== null &&
      deltaCurve[start].deltaSeconds !== null &&
      (deltaCurve[start - 1].deltaSeconds as number) <= (deltaCurve[start].deltaSeconds as number)
    ) {
      start--;
    }
    biggestLossZone = {
      startDist: deltaCurve[start].dist,
      endDist: deltaCurve[maxIdx].dist,
      lostSeconds: maxDelta,
    };
  }

  return {
    lapA: lapA.lapNum,
    lapB: lapB.lapNum,
    deltaCurve,
    totalDeltaSeconds,
    sectorDeltas: {
      sector1: lapB.sector1 - lapA.sector1,
      sector2: lapB.sector2 - lapA.sector2,
      sector3: lapB.sector3 - lapA.sector3,
    },
    biggestGainZone,
    biggestLossZone,
  };
}

// =======================================================================
// 2. Corner detection — steering angle + lateral g threshold, with a
// consecutive-frame debounce, a gap-bridging pass, and an apex speed-drop
// sanity check.
//
// FIXED (Aug 2026, round 1): the original single-frame-threshold version
// misread flat-out straights as corners — curb/road-surface noise on a
// straight could spike gForceLateral over the old 0.3g threshold for one
// frame. Fixed by raising thresholds substantially and requiring several
// consecutive turning frames before treating anything as a corner entry.
//
// FIXED (Aug 2026, round 2): that fix then swallowed real corners — a
// Jeddah lap 4 complex hairpin/chicane at 480-640m (steering to -153°,
// lateral g to 2.97g, min speed 77 km/h) went completely undetected.
// Cause: the driver briefly straightens the wheel for ~8 frames between
// the two apexes of a double-apex corner. The old code treated that gap
// as "corner ended", splitting one real corner into fragments — and each
// fragment's own boundary frame was still mid-corner (slow), so the apex
// speed-drop sanity check compared the apex against a deceptively slow
// "exit" and rejected the whole thing as noise, along with every other
// multi-apex corner on the lap.
//
// Fix: (1) bridge separate turning runs into one corner when the gap
// between them is short (GAP_BRIDGE_METERS) — a brief straightening mid-
// corner shouldn't end the corner; (2) validate the apex speed drop
// against the car's true entry/exit speed — the fastest it was going in
// the REFERENCE_WINDOW_METERS immediately before/after the whole (possibly
// bridged) corner — rather than the corner segment's own boundary frame,
// which can still be mid-corner if bridging occurred.
//
// All speeds in this section (STEER_THRESHOLD_DEG excepted — that's
// degrees, not speed) are km/h always, regardless of the report's
// requested speedUnit — this is detection math, not a display value.
// =======================================================================

const GLAT_THRESHOLD = 1.2; // g — filters out straight-line curb/road noise
const MIN_CONSECUTIVE_TURN_FRAMES = 4; // one noisy frame shouldn't start a corner
const MIN_APEX_SPEED_DROP_KMH = 15; // apex must be genuinely slower than true entry/exit, or it's not a corner — always km/h, independent of report display unit
const GAP_BRIDGE_METERS = 25; // bridge brief straightening within a complex corner (chicanes, hairpin doubles) so one real corner isn't fragmented
const REFERENCE_WINDOW_METERS = 150; // how far to look before/after a corner for its true (straight-line) entry/exit speed

function maxSpeedInWindow(
  frames: TelemetryFrame[],
  centerDist: number,
  direction: 'before' | 'after',
  windowMeters: number,
  fallback: number
): number {
  const lo = direction === 'before' ? centerDist - windowMeters : centerDist;
  const hi = direction === 'before' ? centerDist : centerDist + windowMeters;
  let max = -Infinity;
  for (const f of frames) {
    if (f.dist >= lo && f.dist <= hi) max = Math.max(max, f.speed);
  }
  return Number.isFinite(max) ? max : fallback;
}

export function detectCorners(frames: TelemetryFrame[]): CornerSegment[] {
  const corners: CornerSegment[] = [];
  const isTurning = frames.map(
    (f) => Math.abs(f.steer) > STEER_THRESHOLD_DEG || Math.abs(f.gLat) > GLAT_THRESHOLD
  );

  // Step 1: raw runs of consecutive turning frames (end is exclusive).
  const rawRuns: { start: number; end: number }[] = [];
  let i = 0;
  while (i < frames.length) {
    if (!isTurning[i]) {
      i++;
      continue;
    }
    let end = i;
    while (end < frames.length && isTurning[end]) end++;
    rawRuns.push({ start: i, end });
    i = end;
  }

  // Step 2: bridge runs separated by a short non-turning gap in distance —
  // see header comment for why this matters for double-apex corners.
  const mergedRuns: { start: number; end: number }[] = [];
  for (const run of rawRuns) {
    const last = mergedRuns[mergedRuns.length - 1];
    if (last && frames[run.start].dist - frames[last.end - 1].dist <= GAP_BRIDGE_METERS) {
      last.end = run.end;
    } else {
      mergedRuns.push({ ...run });
    }
  }

  let cornerId = 0;
  for (const run of mergedRuns) {
    const runLength = run.end - run.start;
    if (runLength < MIN_CONSECUTIVE_TURN_FRAMES) continue;

    const segment = frames.slice(run.start, run.end);

    // apex = point of minimum speed within the (possibly bridged) segment
    let apexIdx = 0;
    let minSpeed = Infinity;
    for (let j = 0; j < segment.length; j++) {
      if (segment[j].speed < minSpeed) {
        minSpeed = segment[j].speed;
        apexIdx = j;
      }
    }

    // Sanity check: compare the apex against the car's true entry/exit
    // speed — the fastest it was going in the window immediately before
    // and after this corner — not the segment's own boundary frame, which
    // can still be mid-corner (slow) if this corner was bridged from
    // multiple turning runs.
    const entrySpeed = segment[0].speed;
    const exitSpeed = segment[segment.length - 1].speed;
    const entryRef = maxSpeedInWindow(frames, frames[run.start].dist, 'before', REFERENCE_WINDOW_METERS, entrySpeed);
    const exitRef = maxSpeedInWindow(frames, frames[run.end - 1].dist, 'after', REFERENCE_WINDOW_METERS, exitSpeed);
    const referenceSpeed = Math.min(entryRef, exitRef);
    if (referenceSpeed - minSpeed < MIN_APEX_SPEED_DROP_KMH) {
      continue;
    }

    const avgSteer = segment.reduce((sum, f) => sum + f.steer, 0) / segment.length;

    corners.push({
      id: cornerId++,
      entryDist: frames[run.start].dist,
      apexDist: segment[apexIdx].dist,
      exitDist: frames[run.end - 1].dist,
      direction: avgSteer < 0 ? 'left' : 'right', // sign convention depends on game's steer field — verify against a known left-hander
    });
  }

  return corners;
}

// =======================================================================
// 2b. Straight detection — the gaps between corners (and before the first
// / after the last corner) are the straights. Kept simple: no separate
// thresholding, just the complement of the corner list along the lap.
// Very short gaps between corners (e.g. two corners in quick succession
// that didn't get bridged by detectCorners' GAP_BRIDGE_METERS) aren't
// worth surfacing as their own "straight" — there's nothing to coach in a
// 20m connecting kerb.
//
// FIXED (2026-10): a straight used to end at the next corner's steering
// ENTRY. But the driver brakes before turning in, so the last stretch of
// every straight was a braking zone — and that dragged avgThrottle down to
// 69-81% on straights where the driver was flat-out the whole way, which
// then produced "check for an unnecessary lift" tips that were really just
// the braking zone. A straight now ends at the next corner's BRAKE POINT
// (pass brakePointByCornerId from analyzeBraking), falling back to the
// steering entry when no brake point is known.
// =======================================================================

const MIN_STRAIGHT_METERS = 50;

export function detectStraights(
  frames: TelemetryFrame[],
  corners: CornerSegment[],
  brakePointByCornerId?: Map<number, number>
): StraightSegment[] {
  const lapEnd = frames[frames.length - 1]?.dist ?? 0;
  const straights: StraightSegment[] = [];
  let straightId = 0;

  let cursor = 0;
  let afterCornerId: number | null = null;

  for (const corner of corners) {
    const brakePoint = brakePointByCornerId?.get(corner.id);
    // The straight ends where braking starts. Never before the cursor, and
    // never after the corner's own entry.
    const straightEnd = Math.max(cursor, Math.min(corner.entryDist, brakePoint ?? corner.entryDist));
    if (straightEnd - cursor >= MIN_STRAIGHT_METERS) {
      straights.push({
        id: straightId++,
        startDist: cursor,
        endDist: straightEnd,
        afterCornerId,
        beforeCornerId: corner.id,
      });
    }
    cursor = corner.exitDist;
    afterCornerId = corner.id;
  }

  if (lapEnd - cursor >= MIN_STRAIGHT_METERS) {
    straights.push({
      id: straightId++,
      startDist: cursor,
      endDist: lapEnd,
      afterCornerId,
      beforeCornerId: null,
    });
  }

  return straights;
}

function framesInRange(frames: TelemetryFrame[], startDist: number, endDist: number): TelemetryFrame[] {
  return frames.filter((f) => f.dist >= startDist && f.dist <= endDist);
}

// Resolves a raw F1 UDP track name (e.g. "Sakhir", "Abu Dhabi", "Austin")
// to its canonical name + nominal turn count, for the track sanity check
// below. Deliberately reuses pitboss.f1_track_name_aliases — the same
// alias table telemetry-ingest already relies on to resolve track_id for
// setup submissions — rather than a second, separate name-matching
// heuristic. Turn counts live in pitboss.tracks.turns (added specifically
// for this check — see its column comment).
async function getTrackTurnsForRawName(rawName: string): Promise<{ name: string; turns: number } | null> {
  const needle = rawName.trim().toLowerCase();
  if (!needle) return null;

  const supabase = createAdminClient();
  const { data: alias } = await supabase
    .schema('pitboss')
    .from('f1_track_name_aliases')
    .select('track_id')
    .eq('game_track_name', needle)
    .maybeSingle();
  if (!alias) return null;

  const { data: track } = await supabase
    .schema('pitboss')
    .from('tracks')
    .select('name, turns')
    .eq('id', alias.track_id)
    .maybeSingle();
  if (!track || track.turns == null) return null;

  return { name: track.name, turns: track.turns };
}

export function analyzeStraight(
  frames: TelemetryFrame[],
  straight: StraightSegment,
  comparison: LapComparison | null
): StraightAnalysis {
  const zone = framesInRange(frames, straight.startDist, straight.endDist);

  // topSpeed is always km/h at this stage — converted to the report's
  // requested speedUnit once, at the buildCoachingReport boundary.
  let topSpeed = 0;
  let topSpeedDist = straight.startDist;
  for (const f of zone) {
    if (f.speed > topSpeed) {
      topSpeed = f.speed;
      topSpeedDist = f.dist;
    }
  }

  // avgThrottle is measured over the FLAT-OUT portion of the straight: from
  // the first frame where the driver reaches full throttle to the end of
  // the straight (which now stops at the next brake point). The ramp-up
  // out of the previous corner is deliberately excluded — it's exit
  // technique, already covered by that corner's throttle analysis, and
  // counting it made every straight look like it had a lift. If the driver
  // never reaches full throttle on this straight, the whole zone is used.
  // A value below ~0.9 therefore means genuine lifts mid-straight.
  const firstFlatOutIdx = zone.findIndex((f) => f.throttle >= FULL_THROTTLE_THRESHOLD);
  const flatOutZone = firstFlatOutIdx >= 0 ? zone.slice(firstFlatOutIdx) : zone;
  const avgThrottle =
    flatOutZone.length > 0 ? flatOutZone.reduce((s, f) => s + f.throttle, 0) / flatOutZone.length : 0;

  const drsFrames = zone.filter((f) => f.drs);
  const drsActivePercent = zone.length > 0 ? drsFrames.length / zone.length : 0;

  // Time delta across this straight's distance range, sourced from the
  // already-computed lap comparison rather than recomputing anything —
  // consistent with the rule that the LLM (and this helper) never invents
  // numbers, only reads what compareLaps already produced. Skips any
  // deltaCurve point whose value is null (unreliable — see DeltaPoint) so
  // a single capture gap inside this straight's range doesn't silently
  // corrupt the delta; if the endpoints we need are unreliable, the
  // result is null rather than a wrong number.
  let deltaVsReferenceSeconds: number | null = null;
  if (comparison) {
    const inRange = comparison.deltaCurve.filter((p) => p.dist >= straight.startDist && p.dist <= straight.endDist);
    if (inRange.length >= 2) {
      const first = inRange[0].deltaSeconds;
      const last = inRange[inRange.length - 1].deltaSeconds;
      if (first !== null && last !== null) {
        deltaVsReferenceSeconds = last - first;
      }
    }
  }

  return {
    straightId: straight.id,
    lengthMeters: straight.endDist - straight.startDist,
    topSpeed,
    topSpeedDist,
    avgThrottle,
    drsActivePercent,
    deltaVsReferenceSeconds,
  };
}

// =======================================================================
// 3. Braking analysis per corner
// =======================================================================

export function analyzeBraking(
  frames: TelemetryFrame[],
  corner: CornerSegment,
  previousCorner: CornerSegment | null
): BrakingAnalysis {
  // Look slightly before corner entry for the actual brake point, which
  // usually precedes the steering input. Clamped to the previous corner's
  // exit so a close-together sequence — the same case GAP_BRIDGE_METERS
  // exists to handle for detection (chicanes, tight corner sequences) —
  // doesn't pull braking/trail-brake frames that actually belong to the
  // prior corner into this one's analysis. Without the clamp, a fixed
  // 150m lookback can extend past the previous corner's exit whenever two
  // corners sit closer together than 150m.
  const searchStart = previousCorner
    ? Math.max(corner.entryDist - 150, previousCorner.exitDist)
    : Math.max(0, corner.entryDist - 150);
  const zone = framesInRange(frames, searchStart, corner.apexDist);

  const brakingFrames = zone.filter((f) => f.brake > BRAKE_THRESHOLD);
  const brakePointDist = brakingFrames[0]?.dist ?? corner.entryDist;
  const brakePeakPressure = brakingFrames.reduce((max, f) => Math.max(max, f.brake), 0);
  const brakeDurationMeters =
    brakingFrames.length > 0
      ? brakingFrames[brakingFrames.length - 1].dist - brakingFrames[0].dist
      : 0;

  const trailBrakeFrames = brakingFrames.filter((f) => Math.abs(f.steer) > STEER_THRESHOLD_DEG);
  const trailBrakePercent = brakingFrames.length > 0 ? trailBrakeFrames.length / brakingFrames.length : 0;

  const cornerFrames = framesInRange(frames, corner.entryDist, corner.exitDist);
  const minSpeedInCorner = cornerFrames.reduce((min, f) => Math.min(min, f.speed), Infinity);

  return {
    cornerId: corner.id,
    brakePointDist,
    brakePeakPressure,
    brakeDurationMeters,
    trailBrakePercent,
    // Always km/h at this stage — converted to the report's requested
    // speedUnit once, at the buildCoachingReport boundary.
    minSpeedInCorner: Number.isFinite(minSpeedInCorner) ? minSpeedInCorner : 0,
  };
}

// =======================================================================
// 4. Throttle analysis per corner
//
// FIXED (2026-10): throttleApplicationDist used to be the first frame at or
// after the apex with throttle > 10%. Drivers are almost always already
// past 10% (maintenance throttle) at the apex, so the result was ~0m for
// every corner on every lap — a number that carried no information. The
// pickup point is now the first frame at/after the apex where throttle
// stays at or above THROTTLE_PICKUP_THRESHOLD (30%) for
// THROTTLE_PICKUP_MIN_FRAMES consecutive frames. 0m therefore genuinely
// means "already on meaningful throttle at the apex".
// =======================================================================

const THROTTLE_PICKUP_THRESHOLD = 0.3;
const THROTTLE_PICKUP_MIN_FRAMES = 2;

export function analyzeThrottle(frames: TelemetryFrame[], corner: CornerSegment, nextCorner: CornerSegment | null): ThrottleAnalysis {
  const searchEnd = nextCorner ? nextCorner.entryDist : corner.exitDist + 300;
  const zone = framesInRange(frames, corner.apexDist, searchEnd);

  let throttleApplicationDist = corner.apexDist;
  for (let i = 0; i < zone.length; i++) {
    let sustained = true;
    for (let k = 0; k < THROTTLE_PICKUP_MIN_FRAMES; k++) {
      const f = zone[i + k];
      if (!f || f.throttle < THROTTLE_PICKUP_THRESHOLD) {
        sustained = false;
        break;
      }
    }
    if (sustained) {
      throttleApplicationDist = zone[i].dist;
      break;
    }
  }
  const distFromApexToThrottle = Math.max(0, throttleApplicationDist - corner.apexDist);

  const fullThrottleFrame = zone.find((f) => f.throttle >= FULL_THROTTLE_THRESHOLD);
  const fullThrottleDist = fullThrottleFrame?.dist ?? null;

  // Smoothness: lower variance in frame-to-frame throttle delta = smoother
  // ramp, not a jabby/inconsistent application. Measured from the pickup
  // point to full throttle (or the end of the search window), so coasting
  // frames before the pickup don't count as part of the ramp.
  const rampFrames = zone.filter(
    (f) => f.dist >= throttleApplicationDist && f.dist <= (fullThrottleDist ?? searchEnd)
  );
  let smoothness = 1;
  if (rampFrames.length > 2) {
    const deltas: number[] = [];
    for (let i = 1; i < rampFrames.length; i++) deltas.push(rampFrames[i].throttle - rampFrames[i - 1].throttle);
    const mean = deltas.reduce((s, d) => s + d, 0) / deltas.length;
    const variance = deltas.reduce((s, d) => s + (d - mean) ** 2, 0) / deltas.length;
    smoothness = Math.max(0, 1 - variance * 20); // scaled heuristic, not a calibrated physical unit
  }

  return {
    cornerId: corner.id,
    throttleApplicationDist,
    distFromApexToThrottle,
    fullThrottleDist,
    applicationSmoothness: smoothness,
  };
}

// =======================================================================
// 5. Consistency & mistake detection
//
// FIXED (2026-10): the over-rev check compared RPM against a hardcoded
// 11500 "redline". The real limiter on these cars sits above that (the
// live panel showed 11362 RPM at 91% of max, i.e. a limiter around
// 12,500), so ordinary revs of 11504-11563 in 4th-6th gear were being
// reported as "missed upshift" — false positives on nearly every lap.
//
// The limiter is now estimated from the data itself: the highest RPM seen
// anywhere in the session (estimateLimiterRpm). An over-rev is only
// reported when the engine sits within LIMITER_FRACTION of that limiter, at
// near-full throttle, in the SAME gear, for at least OVERREV_MIN_FRAMES
// consecutive frames — i.e. a real sustained hit on the limiter, not a
// momentary brush of it during a normal shift. This is a heuristic: if a
// driver never touches the limiter all session, the estimate is just their
// highest shift point and sustained holds there are still the right thing
// to flag, but the wording "rev limiter" is then approximate.
// =======================================================================

const DEFAULT_LIMITER_RPM = 12000; // used only when a session has no usable RPM data
const LIMITER_FRACTION = 0.995;
const OVERREV_MIN_FRAMES = 3;
const OVERREV_MIN_THROTTLE = 0.9;

function estimateLimiterRpm(session: TelemetrySession): number {
  let max = 0;
  for (const lap of session.laps) {
    for (const f of lap.frames) {
      if (f.rpm > max) max = f.rpm;
    }
  }
  return max > 0 ? max : DEFAULT_LIMITER_RPM;
}

// =======================================================================
// FIXED (2026-09): ISSUE_MERGE_DIST_METERS (a flat 3m distance threshold)
// merged same-kind issues that were close together in DISTANCE. But
// issues are emitted once per FRAME, and frame-to-frame distance scales
// with speed (and with capture rate, which this same file documents
// elsewhere as bursty/variable — see SOURCE_GAP_UNRELIABLE_SECONDS's
// comment). At typical corner-exit/straight-line speeds, consecutive
// frames are commonly 5-8m apart — already past the old 3m threshold —
// so a single sustained over-rev or sustained snap-correction run failed
// to merge and was reported as N separate issues, one per frame.
//
// FIX: merge by FRAME ADJACENCY instead of raw distance. Frame adjacency
// is invariant to speed and capture-rate variance. Merging happens inline
// in detectIssues (via the local `emit` helper below) since it needs the
// frame index, which isn't part of DetectedIssue's public shape.
// =======================================================================

// Consecutive same-kind issues within this many FRAMES (not meters) of
// each other are one sustained condition, not N separate events.
const ISSUE_MERGE_FRAME_GAP = 2;

export function detectIssues(
  frames: TelemetryFrame[],
  limiterRpm: number = DEFAULT_LIMITER_RPM,
  speedUnit: SpeedUnit = 'kph'
): DetectedIssue[] {
  const issues: DetectedIssue[] = [];
  const unitLabel = speedUnitLabel(speedUnit);

  // Tracks, per issue kind, the frame index at which that kind was last
  // emitted/extended and the index into `issues` of that entry — so a new
  // detection can extend the existing entry (bump endDist, escalate
  // severity) instead of always pushing a new one.
  const lastFrameIndexByKind = new Map<DetectedIssue['kind'], number>();
  const lastIssueIndexByKind = new Map<DetectedIssue['kind'], number>();

  function emit(kind: DetectedIssue['kind'], frameIdx: number, dist: number, severity: 'minor' | 'major', note: string) {
    const lastFrameIdx = lastFrameIndexByKind.get(kind);
    const lastIssueIdx = lastIssueIndexByKind.get(kind);
    if (
      lastFrameIdx !== undefined &&
      lastIssueIdx !== undefined &&
      frameIdx - lastFrameIdx <= ISSUE_MERGE_FRAME_GAP
    ) {
      // Extend the existing sustained-condition entry rather than
      // starting a new one.
      const existing = issues[lastIssueIdx];
      existing.endDist = dist;
      if (severity === 'major') existing.severity = 'major';
    } else {
      issues.push({ kind, dist, severity, note });
      lastIssueIndexByKind.set(kind, issues.length - 1);
    }
    lastFrameIndexByKind.set(kind, frameIdx);
  }

  let limiterRun = 0; // consecutive frames sitting on the limiter in one gear

  for (let i = 2; i < frames.length; i++) {
    const prev = frames[i - 1];
    const curr = frames[i];

    // Lockup heuristic: heavy braking + longitudinal g suddenly collapses
    // (locked tyres generate less stopping force than a rolling tyre at
    // the grip limit) while speed keeps dropping. Not a direct wheel-lock
    // signal — F1 UDP doesn't expose per-wheel slip ratio — so this is a
    // proxy, not a certainty. Validate against a known locked-wheel replay
    // before trusting severity labels.
    if (curr.brake > 0.8 && prev.brake > 0.8) {
      const gDrop = prev.gLon - curr.gLon; // gLon expected negative under braking; a sudden move toward 0 = grip loss
      if (gDrop > 0.4 && curr.speed < prev.speed) {
        emit(
          'lockup',
          i,
          curr.dist,
          gDrop > 0.7 ? 'major' : 'minor',
          `Possible lockup — braking g dropped ${gDrop.toFixed(2)}g while still on the brakes.`
        );
      }
    }

    // Snap correction: large, fast steering reversal at speed — proxy for
    // a near-spin or correction after losing the rear. Threshold is a
    // starting guess. curr.speed (km/h internally) is converted + labeled
    // here since this note text is user-facing and needs to match
    // whatever unit the rest of the report is displayed in.
    const steerDelta = curr.steer - prev.steer;
    if (Math.abs(steerDelta) > 25 && curr.speed > 30 && Math.sign(steerDelta) !== Math.sign(prev.steer - frames[i - 2].steer)) {
      const displaySpeed = convertSpeed(curr.speed, speedUnit);
      emit(
        'snap_correction',
        i,
        curr.dist,
        Math.abs(steerDelta) > 45 ? 'major' : 'minor',
        `Sharp steering correction (${steerDelta.toFixed(0)}° in one frame) at ${displaySpeed.toFixed(0)} ${unitLabel} — possible rear-end slide.`
      );
    }

    // Over-rev: the engine sitting on the limiter for several consecutive
    // frames in one gear at near-full throttle — a missed upshift, not a
    // brief touch during a normal shift. See the section header for why
    // this is relative to the session's observed max RPM.
    const atLimiter =
      curr.rpm >= limiterRpm * LIMITER_FRACTION &&
      curr.throttle >= OVERREV_MIN_THROTTLE &&
      prev.gear === curr.gear;
    limiterRun = atLimiter ? limiterRun + 1 : 0;
    if (limiterRun >= OVERREV_MIN_FRAMES) {
      emit(
        'engine_over_rev',
        i,
        curr.dist,
        'minor',
        `Sat on the rev limiter (${Math.round(curr.rpm)} RPM) in gear ${curr.gear} — shift up earlier.`
      );
    }
  }

  return issues;
}

