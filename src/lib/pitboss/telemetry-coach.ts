/**
 * PitBoss — Telemetry Analysis & Coach Engine
 * ----------------------------------------------
 * Post-session analysis over TelemetrySession data (from getTelemetrySession
 * in lib/telemetry.ts). Produces structured coaching insights covering:
 *   1. Lap comparison (delta-over-distance, sector deltas)
 *   2. Corner detection, braking/throttle technique per corner
 *   2b. Straight detection (the gaps between corners) — top speed, throttle
 *       discipline, DRS usage, and time delta vs a reference lap
 *   3. Consistency & mistake detection (lockups, snap corrections)
 *   4. Coaching narrative — summaryText, a note + a short suggestion for
 *      each corner AND each straight, plus top-level suggestions, are
 *      generated by the PitBoss LLM (pbInfer, mode 'reasoning') from the
 *      structured output of 1-3 above. The detection/analysis math itself
 *      stays fully deterministic — the LLM only writes the prose that
 *      interprets those numbers, it never invents the numbers.
 *   5. Track sanity check — cross-references the detected corner count
 *      against F1_TRACKS' known turn count for this circuit, and appends
 *      a caveat to the summary if detection looks substantially
 *      incomplete (see "Track sanity check" section below).
 *   6. Frame-density gate — a lap whose telemetry capture is too sparse
 *      (see MIN_FRAMES_PER_SECOND below) can't support any of the above
 *      trustworthily. Detected up front and short-circuits to an explicit
 *      "too sparse to analyze" report instead of silently running corner
 *      detection / comparison / narrative generation over data with
 *      multi-second blackouts in it.
 *
 * SERVER-ONLY: this file calls pbInfer, which reads PITBOSS_INTERNAL_KEY.
 * Never import this from a 'use client' component — see the recharts /
 * supabase-server bundling incident in TelemetryDashboard.tsx for why that
 * class of mistake is easy to make and hard to spot until deploy. Call
 * buildCoachingReport from a Server Component or Route Handler and pass
 * the resulting CoachingReport down as props/JSON instead.
 *
 * KNOWN GAP — track limits detection: TelemetryFrame.surfaceType exists
 * (see lib/telemetry-types.ts) but is optional and currently always
 * undefined in practice — the upstream aggregator that builds
 * raw_payload.telemetry doesn't copy CarTelemetryData.surfaceType through
 * yet (see the comment in lib/telemetry.ts's reshapeFrame). Without it,
 * "went off track" can only be inferred indirectly (e.g. a lap flagged
 * !lapValid), not pinpointed to a specific corner.
 *
 * KNOWN GAP — car-class redline lookup (see REDLINE_RPM_BY_CLASS below):
 * the field name/values for a session's car class haven't been confirmed
 * against the live TelemetrySession type, so the lookup currently reads
 * off an `any`-cast property. Verify and replace once confirmed.
 */

