/**
 * PitBoss — Telemetry Analysis & Coach Engine
 * ----------------------------------------------
 * Post-session analysis over TelemetrySession data (from getTelemetrySession
 * in lib/telemetry.ts). Produces structured coaching insights covering:
 *   1. Lap comparison (delta-over-distance, sector deltas)
 *   2. Corner detection, braking/throttle technique per corner
 *   2b. Straight detection (the gaps between corners, ending at the next
 *       corner's BRAKE POINT, not its steering entry) — top speed, throttle
 *       discipline over the flat-out portion, DRS usage, and time delta vs
 *       a reference lap
 *   3. Consistency & mistake detection (lockups, snap corrections, sustained
 *      rev-limiter hits)
 *   4. Coaching narrative — summaryText, a note + a short suggestion for
 *      each corner AND each straight, plus top-level suggestions, are
 *      generated by an LLM from the structured output of 1-3 above. The
 *      detection/analysis math itself stays fully deterministic — the LLM
 *      only writes the prose that interprets those numbers, it never
 *      invents the numbers. Provider order (see generateCoachingNarrative):
 *        a. Claude directly (ANTHROPIC_API_KEY)
 *        b. Groq directly (GROQ_API_KEY) — free-tier fallback
 *        c. deterministic template
 *      The old pbInfer / pitboss-proxy path was removed: its worker budgets
 *      (5s Groq + 10s OpenRouter + 6s paid, plus 3s live-model-list lookups
 *      per tier) can exceed the 25s client timeout and it never completed a
 *      coach-sized request.
 *   5. Track sanity check — cross-references the detected corner count
 *      against pitboss.tracks.turns for this circuit and appends a caveat to
 *      the summary if detection looks substantially incomplete.
 *   6. Frame-density gate — a lap whose telemetry capture is too sparse
 *      (see MIN_FRAMES_PER_SECOND below) can't support any of the above
 *      trustworthily. Detected up front and short-circuits to an explicit
 *      "too sparse to analyze" report.
 *
 * SERVER-ONLY: this file reads ANTHROPIC_API_KEY / GROQ_API_KEY and calls
 * the admin Supabase client. Never import it from a 'use client' component.
 * Call buildCoachingReport from a Server Component or Route Handler and pass
 * the resulting CoachingReport down as props/JSON instead.
 *
 * KNOWN GAP — track limits detection: TelemetryFrame.surfaceType exists
 * (see lib/telemetry-types.ts) but is optional and currently always
 * undefined in practice. Without it, "went off track" can only be inferred
 * indirectly (e.g. a lap flagged !lapValid), not pinpointed to a corner.
 */

